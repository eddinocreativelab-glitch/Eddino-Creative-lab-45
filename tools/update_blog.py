#!/usr/bin/env python3
"""
EDDINO CREATIVE LAB - BLOG INDEX BUILDER
========================================

What it does
  Reads every .html file in blog/posts/ and writes blog/posts.js, which is the
  list the Blog page shows. Run it after you add, edit, rename or delete a post.

How to run
  Windows : double-click update-blog.bat in the site folder (needs Python, see README.txt)
  Any OS  : python tools/update_blog.py      (run from the site folder)

Rules for a post (the values are read from the <head> of the post file)
  <title>                         -> the post title on the Blog page (required)
  <meta name="description">       -> the short summary on the Blog page (required)
  <meta name="date" content="YYYY-MM-DD">  -> publication date (required)
  <meta name="category" ...>      -> small label above the title (optional)
  <meta name="status" ...>        -> "published" (default) or "draft" (hidden)

Files whose name starts with "_" (like _template.html) are ignored.
It also writes sitemap.xml (home page + published posts) for search engines.
Only the Python standard library is used: nothing to install.
"""
import datetime
import json
import sys
from html.parser import HTMLParser
from pathlib import Path
from xml.sax.saxutils import escape

SITE = Path(__file__).resolve().parent.parent
POSTS_DIR = SITE / "blog" / "posts"
OUTPUT = SITE / "blog" / "posts.js"
SITEMAP = SITE / "sitemap.xml"
# Public address of the site. Change it here if the domain is different.
SITE_URL = "https://www.eddinocreativelab.com"


class HeadReader(HTMLParser):
    """Collects the <title> text and the <meta name="..."> values of a post."""

    def __init__(self):
        super().__init__()
        self.meta = {}
        self.title = ""
        self._in_title = False

    def handle_starttag(self, tag, attrs):
        attributes = dict(attrs)
        if tag == "title":
            self._in_title = True
        elif tag == "meta" and attributes.get("name"):
            self.meta[attributes["name"].strip().lower()] = (attributes.get("content") or "").strip()

    def handle_endtag(self, tag):
        if tag == "title":
            self._in_title = False

    def handle_data(self, data):
        if self._in_title:
            self.title += data


def read_post(path):
    reader = HeadReader()
    reader.feed(path.read_text(encoding="utf-8"))
    return reader


def write_sitemap(posts):
    """Writes sitemap.xml: the home page and every published blog post."""
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
        f"  <url><loc>{escape(SITE_URL + '/')}</loc></url>",
    ]
    for post in posts:
        lines.append(
            f"  <url><loc>{escape(SITE_URL + '/' + post['file'])}</loc>"
            f"<lastmod>{post['date']}</lastmod></url>"
        )
    lines.append("</urlset>")
    SITEMAP.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    try:
        sys.stdout.reconfigure(errors="replace")
    except AttributeError:
        pass

    if not POSTS_DIR.is_dir():
        print("Folder blog/posts/ not found. Nothing was changed.")
        return 1

    posts = []
    notes = []
    for path in sorted(POSTS_DIR.glob("*.html")):
        if path.name.startswith("_"):
            continue

        head = read_post(path)
        meta = head.meta
        title = head.title.strip()
        status = meta.get("status", "published").lower()

        if status == "draft":
            notes.append(f"{path.name}: draft, not published")
            continue

        problems = []
        if not title:
            problems.append("missing <title>")
        if not meta.get("description"):
            problems.append('missing <meta name="description">')
        date_text = meta.get("date", "")
        try:
            datetime.date.fromisoformat(date_text)
        except ValueError:
            problems.append('missing or wrong <meta name="date"> (write it as YYYY-MM-DD)')

        if problems:
            notes.append(f"{path.name}: NOT published, " + "; ".join(problems))
            continue

        posts.append({
            "slug": path.stem,
            "title": title,
            "description": meta["description"],
            "date": date_text,
            "category": meta.get("category", ""),
            "file": "blog/posts/" + path.name,
        })

    posts.sort(key=lambda post: post["date"], reverse=True)

    header = ("/* Generated by tools/update_blog.py - do not edit by hand.\n"
              " * Edit the files in blog/posts/ instead, then run update-blog.bat again. */\n")
    body = "window.EDDINO_BLOG_POSTS = " + json.dumps(posts, ensure_ascii=False, indent=2) + ";\n"
    OUTPUT.write_text(header + body, encoding="utf-8")

    write_sitemap(posts)

    print(f"Blog index written: {len(posts)} published post(s). sitemap.xml updated.")
    for post in posts:
        print(f"  - {post['date']}  {post['file']}")
    for note in notes:
        print(f"  ! {note}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
